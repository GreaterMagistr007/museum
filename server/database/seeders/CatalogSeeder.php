    /**
     * Посев элементов конкретного типа.
     */
    private function seedType(string $type, array $items): void
    {
        foreach ($items as $index => $item) {
            $record = CatalogItem::where('title', $item['title'])
                ->where('type', $type)
                ->first();

            if ($record) {
                $record->update([
                    'description' => $item['description'],
                    'is_published' => true,
                    'sort_order' => $index,
                ]);
            } else {
                $record = new CatalogItem([
                    'title' => $item['title'],
                    'description' => $item['description'],
                    'is_published' => true,
                    'sort_order' => $index,
                ]);
                $record->type = $type;
                $record->save();
            }
        }
    }
